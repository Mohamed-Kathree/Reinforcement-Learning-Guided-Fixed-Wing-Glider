"""
firmware_sync.py
================
Keeps the flight sketch in step with its sources of truth. Arduino compiles
only files inside the sketch folder, so:

  firmware/protocol/{rlg_protocol.h, rlg_crc8.c, rlg_safety.h, rlg_safety.c}
      -> firmware/flight/src/protocol/   (byte-identical copies; tested sources)
  flighttest/config/calibration.json
      -> firmware/flight/src/generated/calibration_gen.h   (servo neutral,
         direction, full-deflection us, travel limits; rail scaling; baro warm-up)

    python -m flighttest.firmware_sync          # write
    python -m flighttest.firmware_sync --check  # exit 1 if anything is stale

The calibration FILE is the store; the header is a build artefact generated
from it, stamped with a hash, and printed at boot so a board can be matched to
the calibration it carries. (Pushing calibration at run time into NVS, without
reflashing, is a later step.)
"""

from __future__ import annotations

import hashlib
import json
import os

import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from flighttest import calibration as C  # noqa: E402

PROTO_SRC = os.path.join(ROOT, "firmware", "protocol")
PROTO_DST = os.path.join(ROOT, "firmware", "flight", "src", "protocol")
PROTO_FILES = ("rlg_protocol.h", "rlg_crc8.c", "rlg_safety.h", "rlg_safety.c")
CAL_JSON = C.DEFAULT_PATH
CAL_H = os.path.join(ROOT, "firmware", "flight", "src", "generated", "calibration_gen.h")


def calibration_header(cal: dict, raw: bytes) -> str:
    h = hashlib.sha256(raw.replace(b"\r\n", b"\n")).hexdigest()[:12]
    names = C.SERVO_NAMES
    sv = [cal["servos"][n] for n in names]

    def arr(key, ctype="int16_t"):
        return "{" + ", ".join(str(int(s[key])) for s in sv) + "}"

    measured = all(s["measured"] for s in sv)
    r = cal["rail"]
    lines = [
        "/*",
        " * GENERATED by flighttest/firmware_sync.py from flighttest/config/calibration.json.",
        " * Do not edit: change the JSON (the dashboard's Ground Station page writes it) and re-run.",
        " */",
        "#ifndef RLG_CALIBRATION_GEN_H",
        "#define RLG_CALIBRATION_GEN_H",
        "",
        "#include <stdint.h>",
        "",
        f'#define CAL_HASH "{h}"',
        f"#define CAL_VERSION {int(cal['version'])}",
        f"#define CAL_SERVOS_MEASURED {1 if measured else 0}   /* 0: neutrals/directions are placeholders */",
        f"#define CAL_IMU_VERIFIED {1 if cal['imu']['verified'] else 0}",
        f"#define CAL_RAIL_CALIBRATED {1 if r['calibrated'] else 0}",
        "",
        "/* Servo order = protocol order: " + ", ".join(names) + " */",
        f"static const int16_t CAL_NEUTRAL_US[4] __attribute__((unused)) = {arr('neutral_us')};",
        f"static const int8_t  CAL_DIRECTION[4]  __attribute__((unused)) = {arr('direction')};",
        f"static const int16_t CAL_FULL_US[4]    __attribute__((unused)) = {arr('us_full_deflection')};",
        f"static const int16_t CAL_MIN_US[4]     __attribute__((unused)) = {arr('min_us')};",
        f"static const int16_t CAL_MAX_US[4]     __attribute__((unused)) = {arr('max_us')};",
        "",
        f"#define CAL_RAIL_ADC_GPIO {int(r['adc_gpio'])}",
        f"#define CAL_RAIL_SCALE {float(r['scale']):.6f}f",
        f"#define CAL_RAIL_OFFSET_V {float(r['offset_v']):.6f}f",
        f"#define CAL_RAIL_BROWNOUT_V {float(r['brownout_v']):.3f}f",
        f"#define CAL_BARO_WARMUP_MS {int(float(cal['baro']['warmup_s']) * 1000)}u",
        "",
        "#endif /* RLG_CALIBRATION_GEN_H */",
        "",
    ]
    return "\n".join(lines)


def outputs() -> dict[str, bytes]:
    out = {}
    for f in PROTO_FILES:
        with open(os.path.join(PROTO_SRC, f), "rb") as fh:
            out[os.path.join(PROTO_DST, f)] = fh.read().replace(b"\r\n", b"\n")
    with open(CAL_JSON, "rb") as fh:
        raw = fh.read()
    cal = C.load(CAL_JSON)
    out[CAL_H] = calibration_header(cal, raw).encode("utf-8")
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, data in outputs().items():
        cur = open(path, "rb").read().replace(b"\r\n", b"\n") if os.path.exists(path) else None
        if cur != data:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "wb") as fh:
                    fh.write(data)
    if check:
        print("stale: " + ", ".join(stale) if stale else "firmware sources up to date")
        return 1 if stale else 0
    print("wrote: " + (", ".join(stale) if stale else "nothing (up to date)"))
    return 0


if __name__ == "__main__":

    sys.exit(main(sys.argv[1:]))
