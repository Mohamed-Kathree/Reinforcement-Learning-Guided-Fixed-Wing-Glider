"""
codegen.py
==========
Generates both sides of the glider <-> ground protocol from schema.json:

    flighttest/protocol/packets.py      Python: constants, CRC8, encode/decode, stream parser
    firmware/protocol/rlg_protocol.h    C: packed structs, size/offset asserts, constants
    flighttest/protocol/test_vectors.json  sample packets encoded by the Python side

    python -m flighttest.protocol.codegen          # write
    python -m flighttest.protocol.codegen --check  # exit 1 if any output is stale

Nothing here touches hardware. The C header is compiled and checked on the
host by tests/test_flighttest_protocol.py; it has not run on an ESP32.
"""

from __future__ import annotations

import json
import math
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SCHEMA = os.path.join(HERE, "schema.json")
OUT_PY = os.path.join(HERE, "packets.py")
OUT_H = os.path.join(ROOT, "firmware", "protocol", "rlg_protocol.h")
OUT_VEC = os.path.join(HERE, "test_vectors.json")

FMT = {"u8": "B", "u16": "H", "u32": "I", "f32": "f", "i32": "i"}
CTYPE = {"u8": "uint8_t", "u16": "uint16_t", "u32": "uint32_t", "f32": "float", "i32": "int32_t"}
SIZE = {"u8": 1, "u16": 2, "u32": 4, "f32": 4, "i32": 4}
BANNER = "GENERATED by flighttest/protocol/codegen.py from flighttest/protocol/schema.json. Do not edit."


def load_schema() -> dict:
    with open(SCHEMA, encoding="utf-8") as f:
        return json.load(f)


def crc8(data: bytes, poly: int = 0x07, init: int = 0x00) -> int:
    c = init
    for b in data:
        c ^= b
        for _ in range(8):
            c = ((c << 1) ^ poly) & 0xFF if c & 0x80 else (c << 1) & 0xFF
    return c


def layout(packet: dict) -> list[tuple[str, str, int, int]]:
    """[(name, ctype, count, offset)] in wire order."""
    out, off = [], 0
    for f in packet["fields"]:
        n = int(f.get("count", 1))
        out.append((f["name"], f["ctype"], n, off))
        off += SIZE[f["ctype"]] * n
    return out


def struct_fmt(packet: dict) -> str:
    return "<" + "".join(f"{f.get('count', 1)}{FMT[f['ctype']]}" if f.get("count", 1) > 1 else FMT[f["ctype"]]
                         for f in packet["fields"])


def validate(schema: dict) -> None:
    assert schema["sync"] == 0xA5
    assert crc8(b"123456789", schema["crc8"]["poly"], schema["crc8"]["init"]) == schema["crc8"]["check_value_123456789"]
    for p in schema["packets"]:
        names = [f["name"] for f in p["fields"]]
        assert names[:3] == ["sync", "type", "seq"] and names[-1] == "crc8", p["name"]
        size = struct.calcsize(struct_fmt(p))
        assert size <= p["max_bytes"], (p["name"], size)
    used = 0
    for b in schema["status_bits"]:
        mask = ((1 << b["width"]) - 1) << b["lsb"]
        assert not used & mask, f"status bit overlap at {b['name']}"
        used |= mask
    assert max(m["value"] for m in schema["modes"]) < 8, "mode must fit 3 status bits"
    assert [s["index"] for s in schema["servos"]] == list(range(len(schema["servos"])))
    cmd = next(p for p in schema["packets"] if p["name"] == "Command")
    assert next(f for f in cmd["fields"] if f["name"] == "servo_us")["count"] == len(schema["servos"])


# --------------------------------------------------------------------------- Python

def gen_python(schema: dict) -> str:
    L = [f'"""{BANNER}', "", "Wire format: little-endian, packed. CRC8 (poly 0x07, init 0x00) over type..last payload byte.",
         '"""', "", "from __future__ import annotations", "", "import struct", "from dataclasses import dataclass, field",
         "", f"SCHEMA_VERSION = {schema['version']}", f"SYNC = 0x{schema['sync']:02X}",
         f"CRC_POLY = 0x{schema['crc8']['poly']:02X}", f"CRC_INIT = 0x{schema['crc8']['init']:02X}", ""]
    L.append("# Modes")
    for m in schema["modes"]:
        L.append(f"{m['name']} = {m['value']}  # {m['doc']}")
    L.append("MODE_NAMES = {" + ", ".join(f"{m['value']}: \"{m['name']}\"" for m in schema["modes"]) + "}")
    L += ["", "# Servo channels (index = position in Command.servo_us)",
          "SERVOS = ["]
    for s in schema["servos"]:
        L.append(f"    {{\"index\": {s['index']}, \"name\": \"{s['name']}\", \"gpio\": {s['gpio']}, "
                 f"\"type\": \"{s['type']}\", \"min_us\": {s['min_us']}, \"max_us\": {s['max_us']}}},")
    L += ["]", "", "# Safety constants (enforced in firmware/protocol/rlg_safety.c and flighttest/safety.py)"]
    for k, v in schema["safety"].items():
        if not k.startswith("_"):
            L.append(f"{k.upper()} = {v}")
    L += ["", "# Status bitfield", "STATUS_BITS = {"]
    for b in schema["status_bits"]:
        L.append(f"    \"{b['name']}\": ({b['lsb']}, {b['width']}),")
    L += ["}", "", "",
          "def crc8(data: bytes) -> int:",
          "    c = CRC_INIT",
          "    for b in data:",
          "        c ^= b",
          "        for _ in range(8):",
          "            c = ((c << 1) ^ CRC_POLY) & 0xFF if c & 0x80 else (c << 1) & 0xFF",
          "    return c", "", "",
          "def pack_status(**fields: int) -> int:",
          "    out = 0",
          "    for name, value in fields.items():",
          "        lsb, width = STATUS_BITS[name]",
          "        value = min(int(value), (1 << width) - 1)",
          "        out |= value << lsb",
          "    return out", "", "",
          "def unpack_status(status: int) -> dict:",
          "    return {name: (status >> lsb) & ((1 << width) - 1) for name, (lsb, width) in STATUS_BITS.items()}",
          "", ""]
    for p in schema["packets"]:
        fmt = struct_fmt(p)
        payload = [f for f in p["fields"] if f["name"] not in ("sync", "type", "crc8")]
        L.append("@dataclass")
        L.append(f"class {p['name']}:")
        L.append(f'    """{p["direction"]}. {struct.calcsize(fmt)} bytes."""')
        L.append(f"    TYPE = {p['type']}")
        L.append(f'    FMT = "{fmt}"')
        L.append(f"    SIZE = {struct.calcsize(fmt)}")
        for f in payload:
            default = "0.0" if f["ctype"] == "f32" else "0"
            if f.get("count", 1) > 1:
                L.append(f"    {f['name']}: list = field(default_factory=lambda: [{default}] * {f['count']})")
            else:
                L.append(f"    {f['name']}: {'float' if f['ctype'] == 'f32' else 'int'} = {default}")
        L += ["", "    def encode(self) -> bytes:"]
        args = []
        for f in payload:
            args.append(f"*self.{f['name']}" if f.get("count", 1) > 1 else f"self.{f['name']}")
        L.append(f"        body = struct.pack(self.FMT[:-1], SYNC, self.TYPE, {', '.join(args)})")
        L.append("        return body + bytes([crc8(body[1:])])")
        L += ["", "    @classmethod", f"    def decode(cls, data: bytes) -> \"{p['name']}\":",
              "        \"\"\"Raises ValueError on wrong length, sync, type or CRC.\"\"\"",
              "        if len(data) != cls.SIZE:",
              "            raise ValueError(f\"length {len(data)} != {cls.SIZE}\")",
              "        if data[0] != SYNC or data[1] != cls.TYPE:",
              "            raise ValueError(\"bad sync or type\")",
              "        if crc8(data[1:-1]) != data[-1]:",
              "            raise ValueError(\"bad crc\")",
              "        v = struct.unpack(cls.FMT, data)",
              "        i = 2", "        kw = {}"]
        for f in payload:
            n = f.get("count", 1)
            if n > 1:
                L.append(f"        kw[\"{f['name']}\"] = list(v[i:i + {n}])")
                L.append(f"        i += {n}")
            else:
                L.append(f"        kw[\"{f['name']}\"] = v[i]")
                L.append("        i += 1")
        L += ["        return cls(**kw)", "", ""]
    L += ["PACKET_TYPES = {" + ", ".join(f"{p['name']}.TYPE: {p['name']}" for p in schema["packets"]) + "}", "", "",
          "class StreamParser:",
          '    """Feeds arbitrary byte chunks; yields whole, CRC-checked packets.',
          "",
          "    Hunts for SYNC, reads the fixed length for the packet type, checks the",
          "    CRC and silently drops anything that fails (counted in .dropped).",
          "    Never blocks: a partial packet just waits in the buffer for more bytes.",
          '    """', "",
          "    def __init__(self) -> None:",
          "        self.buf = bytearray()",
          "        self.dropped = 0",
          "        self.accepted = 0", "",
          "    def feed(self, chunk: bytes) -> list:",
          "        self.buf += chunk",
          "        out = []",
          "        while True:",
          "            i = self.buf.find(SYNC)",
          "            if i < 0:",
          "                self.dropped += len(self.buf) > 0",
          "                self.buf.clear()",
          "                return out",
          "            if i:",
          "                del self.buf[:i]",
          "            if len(self.buf) < 2:",
          "                return out",
          "            cls = PACKET_TYPES.get(self.buf[1])",
          "            if cls is None:",
          "                del self.buf[:1]",
          "                self.dropped += 1",
          "                continue",
          "            if len(self.buf) < cls.SIZE:",
          "                return out",
          "            frame = bytes(self.buf[:cls.SIZE])",
          "            try:",
          "                out.append(cls.decode(frame))",
          "                del self.buf[:cls.SIZE]",
          "                self.accepted += 1",
          "            except ValueError:",
          "                del self.buf[:1]  # resync from the next byte",
          "                self.dropped += 1", ""]
    return "\n".join(L)


# --------------------------------------------------------------------------- C

def gen_c(schema: dict) -> str:
    L = ["/*", f" * {BANNER}", " *",
         " * rlg_protocol.h -- glider <-> ground packets. Little-endian, packed, no padding.",
         " * HOST-TESTED ONLY (tests/test_flighttest_protocol.py compiles it with gcc and checks",
         " * sizes, offsets and CRC against the Python side). Not yet run on an ESP32.",
         " */", "#ifndef RLG_PROTOCOL_H", "#define RLG_PROTOCOL_H", "", "#include <stddef.h>", "#include <stdint.h>", "",
         f"#define RLG_SCHEMA_VERSION {schema['version']}", f"#define RLG_SYNC 0x{schema['sync']:02X}u",
         f"#define RLG_CRC_POLY 0x{schema['crc8']['poly']:02X}u", f"#define RLG_CRC_INIT 0x{schema['crc8']['init']:02X}u", "",
         "typedef enum {"]
    for m in schema["modes"]:
        L.append(f"    RLG_MODE_{m['name']} = {m['value']},  /* {m['doc']} */")
    L += ["} rlg_mode_t;", "", f"#define RLG_NUM_SERVOS {len(schema['servos'])}"]
    for s in schema["servos"]:
        L.append(f"#define RLG_SERVO_{s['name'].upper()} {s['index']}  /* GPIO{s['gpio']}, {s['type']} */")
    L += ["", "/* Hard travel limits, enforced by rlg_safety.c regardless of what the ground sends. */",
          "static const uint16_t RLG_SERVO_MIN_US[RLG_NUM_SERVOS] __attribute__((unused)) = {" + ", ".join(str(s["min_us"]) for s in schema["servos"]) + "};",
          "static const uint16_t RLG_SERVO_MAX_US[RLG_NUM_SERVOS] __attribute__((unused)) = {" + ", ".join(str(s["max_us"]) for s in schema["servos"]) + "};",
          "static const uint8_t RLG_SERVO_GPIO[RLG_NUM_SERVOS] __attribute__((unused)) = {" + ", ".join(str(s["gpio"]) for s in schema["servos"]) + "};",
          "", "/* Safety constants */"]
    for k, v in schema["safety"].items():
        if not k.startswith("_"):
            L.append(f"#define RLG_{k.upper()} {v}{'f' if isinstance(v, float) else 'u'}")
    L += ["", "/* Status bitfield */"]
    for b in schema["status_bits"]:
        L.append(f"#define RLG_STATUS_{b['name'].upper()}_LSB {b['lsb']}u")
        L.append(f"#define RLG_STATUS_{b['name'].upper()}_MASK 0x{((1 << b['width']) - 1) << b['lsb']:08X}u")
    L.append("")
    for p in schema["packets"]:
        tname = f"rlg_{p['name'].lower()}_t"
        L.append(f"#define RLG_TYPE_{p['name'].upper()} {p['type']}u  /* {p['direction']} */")
        L.append("typedef struct __attribute__((packed)) {")
        for name, ct, n, off in layout(p):
            arr = f"[{n}]" if n > 1 else ""
            L.append(f"    {CTYPE[ct]} {name}{arr};  /* offset {off} */")
        L.append(f"}} {tname};")
        size = struct.calcsize(struct_fmt(p))
        L.append(f"#define RLG_{p['name'].upper()}_SIZE {size}u")
        L.append(f"_Static_assert(sizeof({tname}) == {size}, \"{p['name']} size\");")
        for name, ct, n, off in layout(p):
            L.append(f"_Static_assert(offsetof({tname}, {name}) == {off}, \"{p['name']}.{name} offset\");")
        L.append("")
    L += ["/* CRC8 over p[0..len-1]; call with &pkt.type and (size - 2). rlg_crc8.c */",
          "uint8_t rlg_crc8(const uint8_t *p, size_t len);", "", "#endif /* RLG_PROTOCOL_H */", ""]
    return "\n".join(L)


# --------------------------------------------------------------------------- vectors

def gen_vectors(schema: dict, packets_mod) -> str:
    T, C = packets_mod.Telemetry, packets_mod.Command
    tel = T(seq=513, roll=0.1, pitch=-0.25, yaw=3.0, p=0.01, q=-0.02, r=0.5, alt_baro=12.75, sonar=-1.0,
            lat=-33.93, lon=18.63, vn=1.5, ve=-2.25, rail_v=5.05,
            status=packets_mod.pack_status(mode=packets_mod.FLIGHT, armed=1, airborne=1, gps_fix=2, gps_sats=9,
                                           baro_ref_captured=1, baro_warm=1, rail_v_valid=1))
    cmd = C(seq=65535, mode=packets_mod.BENCH, servo_us=[1500, 1480, 1600, 1520])
    vecs = {"crc8": [{"ascii": "123456789", "crc": schema["crc8"]["check_value_123456789"]},
                     {"hex": "", "crc": packets_mod.crc8(b"")},
                     {"hex": "00", "crc": packets_mod.crc8(b"\x00")},
                     {"hex": "ff", "crc": packets_mod.crc8(b"\xff")},
                     {"hex": "0102a5", "crc": packets_mod.crc8(bytes([1, 2, 0xA5]))}],
            "packets": []}
    for name, pkt in (("Telemetry", tel), ("Command", cmd)):
        d = {k: v for k, v in pkt.__dict__.items()}
        d = {k: ([float(x) for x in v] if isinstance(v, list) and name == "Telemetry" else v) for k, v in d.items()}
        for k, v in list(d.items()):
            if isinstance(v, float) and not math.isfinite(v):
                d[k] = str(v)
        vecs["packets"].append({"name": name, "fields": d, "hex": pkt.encode().hex()})
    return json.dumps(vecs, indent=1) + "\n"


def outputs() -> dict[str, str]:
    schema = load_schema()
    validate(schema)
    py = gen_python(schema)
    ns: dict = {}
    exec(compile(py, OUT_PY, "exec"), ns)

    class M:  # namespace view for gen_vectors
        pass
    for k, v in ns.items():
        setattr(M, k, v)
    return {OUT_PY: py, OUT_H: gen_c(schema), OUT_VEC: gen_vectors(schema, M)}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, text in outputs().items():
        # newline="" keeps CRLF visible; compare ignoring line endings, since a
        # Windows checkout (core.autocrlf) rewrites them without changing content.
        current = open(path, encoding="utf-8", newline="").read() if os.path.exists(path) else None
        if current is None or current.replace("\r\n", "\n") != text:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    if check:
        print("stale: " + ", ".join(stale) if stale else "protocol outputs up to date")
        return 1 if stale else 0
    print("wrote: " + (", ".join(stale) if stale else "nothing (up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
