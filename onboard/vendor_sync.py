"""
vendor_sync.py -- keep the Pi's copies of the controller code identical to the
repository's.

The Pi runs numpy and pyserial only: no gymnasium, JSBSim, torch or
stable-baselines3. The gate, the baseline, the observation helpers and the
packet codec are pure numpy/stdlib, but they import each other through the
env/ and baseline/ packages, and deterministic_rtl.py takes three constants
from env.glider_env (which imports the simulator). So the Pi carries copies in
onboard/vendor/ with exactly these changes:

  - module imports rewritten to onboard.vendor.*;
  - the env.glider_env constant import replaced by onboard/vendor/constants.py,
    generated here from the live values.

Everything else is byte-identical. tests/test_onboard.py runs --check, so a
change to any source module fails the tests until this is re-run.

    python -m onboard.vendor_sync          # write
    python -m onboard.vendor_sync --check  # exit 1 if stale
"""

from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
VENDOR = os.path.join(ROOT, "onboard", "vendor")

SOURCES = {
    "nav_features.py": "env/nav_features.py",
    "wind_estimate.py": "env/wind_estimate.py",
    "wind_gate.py": "baseline/wind_gate.py",
    "wind_gated.py": "baseline/wind_gated.py",
    "deterministic_rtl.py": "baseline/deterministic_rtl.py",
    "packets.py": "flighttest/protocol/packets.py",
}

REWRITES = [
    ("from env.glider_env import SPEED_CMD_CENTRE_MS, SPEED_CMD_MIN_MS, SPEED_CMD_SCALE_MS",
     "from onboard.vendor.constants import SPEED_CMD_CENTRE_MS, SPEED_CMD_MIN_MS, SPEED_CMD_SCALE_MS"),
    ("from env.nav_features import", "from onboard.vendor.nav_features import"),
    ("from env.wind_estimate import", "from onboard.vendor.wind_estimate import"),
    ("from baseline.deterministic_rtl import", "from onboard.vendor.deterministic_rtl import"),
    ("from baseline.wind_gate import", "from onboard.vendor.wind_gate import"),
]

BANNER = ("# GENERATED by onboard/vendor_sync.py from {src}: imports rewritten to onboard.vendor.*,\n"
          "# otherwise identical. Do not edit; edit {src} and re-run the sync.\n")


def constants_module() -> str:
    from env import glider_env as G
    names = ("SPEED_CMD_MIN_MS", "SPEED_CMD_MAX_MS", "SPEED_CMD_CENTRE_MS", "SPEED_CMD_SCALE_MS",
             "BANK_CMD_SCALE_RAD", "ALPHA_TRIM", "V_TRIM", "KV_PITCH")
    lines = ['"""GENERATED by onboard/vendor_sync.py from env/glider_env.py (values, not code)."""', ""]
    lines += [f"{n} = {float(getattr(G, n))!r}" for n in names]
    return "\n".join(lines) + "\n"


def outputs() -> dict[str, str]:
    out = {"__init__.py": '"""Pi-side copies of repository modules; see onboard/vendor_sync.py."""\n',
           "constants.py": constants_module()}
    for dst, src in SOURCES.items():
        text = open(os.path.join(ROOT, src), encoding="utf-8").read().replace("\r\n", "\n")
        for a, b in REWRITES:
            text = text.replace(a, b)
        out[dst] = BANNER.format(src=src) + text
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for name, text in outputs().items():
        path = os.path.join(VENDOR, name)
        cur = open(path, encoding="utf-8").read().replace("\r\n", "\n") if os.path.exists(path) else None
        if cur != text:
            stale.append(name)
            if not check:
                os.makedirs(VENDOR, exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    if check:
        print("stale: " + ", ".join(stale) if stale else "onboard/vendor up to date")
        return 1 if stale else 0
    print("wrote: " + (", ".join(stale) if stale else "nothing (up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
